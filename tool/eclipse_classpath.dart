// Regenerates the Eclipse project (`.project`, `.classpath`, `.settings/`)
// that editor Java tooling (e.g. VS Code's Java extension) uses for the
// repo's Java sources. The real builds use Gradle; this only points editors
// at the jars.
//
// Run with: dart run tool/eclipse_classpath.dart
//
// Needs the Android SDK (found through ANDROID_HOME, ANDROID_SDK_ROOT or the
// default location) with the platform and, for navigation, its sources.
// Libraries (Flutter embedding, AndroidX, OkHttp) are taken from Gradle's
// cache, so build the example and run the Android agent once first; missing
// ones are reported and left out.
import 'dart:io';

/// The plugin's compileSdk (packages/platform_host/android/build.gradle.kts).
const _compileSdk = 36;

/// Source folders, with Eclipse exclusion patterns.
const _sourceFolders = [
  ('packages/platform_host/android/src/main/java', ''),
  // GeneratedPluginRegistrant needs every plugin's classes; left to Gradle.
  (
    'packages/platform_host/example/android/app/src/main/java',
    'io/flutter/plugins/',
  ),
  ('packages/platform_automation/agent/android/src/androidTest/java', ''),
];

/// Plain jars, as (group, artifact, version); a null version takes the
/// newest one in the cache.
const _jars = [
  ('androidx.annotation', 'annotation-jvm', null),
  ('com.squareup.okhttp3', 'okhttp', '4.12.0'),
  ('com.squareup.okio', 'okio-jvm', null),
  ('junit', 'junit', '4.13.2'),
];

/// AARs, as unpacked by Gradle (`<artifact>-<version>`), from the agent's
/// dependencies (packages/platform_automation/agent/android/build.gradle.kts).
const _aars = [
  'runner-1.6.2',
  'monitor-1.7.2',
  'uiautomator-2.3.0',
  'junit-1.2.1',
];

final _home = Platform.environment['HOME']!;
final _gradleCaches = '$_home/.gradle/caches';
final _missing = <String>[];

void main() {
  final root = Platform.script.resolve('../');
  final sdk = _androidSdkRoot();

  final androidJar = '$sdk/platforms/android-$_compileSdk/android.jar';
  if (!File(androidJar).existsSync()) {
    stderr.writeln(
      'Missing $androidJar; install "Android SDK Platform $_compileSdk".',
    );
    exit(1);
  }
  final sources = '$sdk/sources/android-$_compileSdk';
  if (!Directory(sources).existsSync()) {
    _missing.add('Sources for Android $_compileSdk (SDK Manager)');
  }

  final engine = File.fromUri(
    root.resolve('flutter_zero/bin/cache/engine.stamp'),
  ).readAsStringSync().trim();
  final libraries = [
    _mavenJar('io.flutter', 'flutter_embedding_debug', '1.0.0-$engine'),
    for (final (group, artifact, version) in _jars)
      _mavenJar(group, artifact, version),
    for (final aar in _aars) _aarJar(aar),
  ].nonNulls;

  String entry(String path, [String? sourcepath]) =>
      '\t<classpathentry kind="lib" path="$path"'
      '${sourcepath == null ? '' : ' sourcepath="$sourcepath"'}/>';

  File.fromUri(root.resolve('.classpath')).writeAsStringSync('''
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tool/eclipse_classpath.dart. -->
<classpath>
${[for (final (path, excluding) in _sourceFolders) '\t<classpathentry kind="src" path="$path"'
        '${excluding.isEmpty ? '' : ' excluding="$excluding"'}/>'].join('\n')}
\t<!-- android.jar is the whole platform, java.* included, like Android's
\t     bootclasspath; a JRE alongside it would provide java.* twice. The
\t     language level is in .settings/org.eclipse.jdt.core.prefs. -->
${entry(androidJar, Directory(sources).existsSync() ? sources : null)}
${[for (final (jar, sourcesJar) in libraries) entry(jar, sourcesJar)].join('\n')}
\t<classpathentry kind="output" path=".vscode/java-bin"/>
</classpath>
''');

  // The Java extension adds its resource filters back on import.
  File.fromUri(root.resolve('.project')).writeAsStringSync('''
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tool/eclipse_classpath.dart. -->
<projectDescription>
\t<name>platform_host</name>
\t<comment></comment>
\t<projects>
\t</projects>
\t<buildSpec>
\t\t<buildCommand>
\t\t\t<name>org.eclipse.jdt.core.javabuilder</name>
\t\t\t<arguments>
\t\t\t</arguments>
\t\t</buildCommand>
\t</buildSpec>
\t<natures>
\t\t<nature>org.eclipse.jdt.core.javanature</nature>
\t</natures>
</projectDescription>
''');

  // Java 17, like the Gradle builds; with no JRE on the classpath it can't
  // be inferred. String concatenation compiles to StringBuilder, as D8
  // desugars it: android.jar has no StringConcatFactory.
  File.fromUri(root.resolve('.settings/org.eclipse.jdt.core.prefs'))
    ..createSync(recursive: true)
    ..writeAsStringSync('''
eclipse.preferences.version=1
org.eclipse.jdt.core.compiler.codegen.targetPlatform=17
org.eclipse.jdt.core.compiler.codegen.useStringConcatFactory=disabled
org.eclipse.jdt.core.compiler.compliance=17
org.eclipse.jdt.core.compiler.source=17
org.eclipse.jdt.core.compiler.release=disabled
''');

  if (_missing.isNotEmpty) {
    stderr.writeln('Left out (not found):\n  ${_missing.join('\n  ')}');
  }
}

/// A jar from Gradle's module cache, and its sources jar if downloaded.
(String, String?)? _mavenJar(String group, String artifact, String? version) {
  final dir = Directory('$_gradleCaches/modules-2/files-2.1/$group/$artifact');
  final versions = dir.existsSync()
      ? [for (final d in dir.listSync().whereType<Directory>()) _name(d)]
      : <String>[];
  version ??= (versions..sort(_compareVersions)).lastOrNull;
  if (version == null || !versions.contains(version)) {
    _missing.add('$group:$artifact:${version ?? '*'}');
    return null;
  }
  String? find(String name) =>
      Directory('${dir.path}/$version')
          .listSync(recursive: true)
          .whereType<File>()
          .where((f) => _name(f) == name)
          .firstOrNull
          ?.path;
  final jar = find('$artifact-$version.jar');
  if (jar == null) {
    _missing.add('$group:$artifact:$version');
    return null;
  }
  return (jar, find('$artifact-$version-sources.jar'));
}

/// An AAR's classes.jar, as unpacked by Gradle's transforms.
(String, String?)? _aarJar(String name) {
  for (final caches in Directory(_gradleCaches).listSync()) {
    final transforms = Directory('${caches.path}/transforms');
    if (!transforms.existsSync()) continue;
    for (final transform in transforms.listSync()) {
      final jar = File('${transform.path}/transformed/$name/jars/classes.jar');
      if (jar.existsSync()) return (jar.path, null);
    }
  }
  _missing.add('$name (AAR)');
  return null;
}

String _name(FileSystemEntity entity) =>
    entity.uri.pathSegments.lastWhere((segment) => segment.isNotEmpty);

/// Orders versions by their numeric parts, so 1.10 sorts after 1.9.
int _compareVersions(String a, String b) {
  List<int> parts(String v) => [
    for (final p in v.split(RegExp(r'[.-]'))) int.tryParse(p) ?? -1,
  ];
  final pa = parts(a), pb = parts(b);
  for (var i = 0; i < pa.length && i < pb.length; i++) {
    if (pa[i] != pb[i]) return pa[i].compareTo(pb[i]);
  }
  return pa.length.compareTo(pb.length);
}

String _androidSdkRoot() {
  final environment = Platform.environment;
  final path =
      environment['ANDROID_HOME'] ??
      environment['ANDROID_SDK_ROOT'] ??
      (Platform.isMacOS ? '$_home/Library/Android/sdk' : '$_home/Android/Sdk');
  return path.endsWith('/') ? path.substring(0, path.length - 1) : path;
}
